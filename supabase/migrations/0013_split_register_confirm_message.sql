-- 0013_split_register_confirm_message.sql
-- แยกข้อความยืนยันลงทะเบียน ออกจากเรื่องสลิปโอนเงิน เป็น 2 บับเบิลแยกกัน (เดิมรวมเป็นข้อความเดียว)
-- match ทั้งด้วยชื่อกฎ (ถ้ายังไม่เปลี่ยน) และด้วย keyword เดิม (เผื่อเปลี่ยนชื่อกฎไปแล้ว)

update auto_replies
set messages = '[
  {"type":"text","text":"ขอบคุณมากครับ คุณ {name}\nน้องพัสดุได้รับข้อมูลการลงทะเบียนแล้ว ✅\nทีมงานจะตรวจสอบและยืนยันกลับภายใน 1-2 วันทำการครับ"},
  {"type":"text","text":"💳 หากชำระเงินแล้ว ส่งรูปสลิปการโอนเงินเข้ามาในแชทนี้ได้เลยครับ ระบบจะตรวจสอบให้อัตโนมัติ"}
]'::jsonb
where name = 'ยืนยันลงทะเบียน (คุณ/สังกัด/หลักสูตร)'
   or 'ลงทะเบียนเรียบร้อย' = any(keywords)
returning id, name, messages;
